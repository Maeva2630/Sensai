from __future__ import annotations

import logging
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

from .chunking import DocumentChunker
from .embeddings import EmbeddingGenerator
from .ingestion import ArchiveIngestionResult, DocumentIngestor, IngestedDocument
from .storage import DEFAULT_TOP_K, LocalVectorStore, MetadataFilter, SearchResult


DEFAULT_CONTEXT_CHARACTER_BUDGET = 4000
DEFAULT_RELEVANCE_THRESHOLD = 0.35

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class RAGContextConfig:
    """Controls how much retrieved evidence is passed to the chat model."""

    top_k: int = DEFAULT_TOP_K
    max_context_characters: int = DEFAULT_CONTEXT_CHARACTER_BUDGET
    relevance_threshold: float = DEFAULT_RELEVANCE_THRESHOLD

    def __post_init__(self) -> None:
        if self.top_k <= 0:
            raise ValueError("top_k must be greater than zero.")
        if self.max_context_characters < 300:
            raise ValueError("max_context_characters must be at least 300.")
        if not math.isfinite(self.relevance_threshold) or not -1.0 <= self.relevance_threshold <= 1.0:
            raise ValueError("relevance_threshold must be a finite value between -1 and 1.")


@dataclass(frozen=True)
class IndexingResult:
    """The outcome of indexing one source document."""

    document: IngestedDocument
    chunk_count: int
    inserted_chunk_count: int


@dataclass(frozen=True)
class ArchiveIndexingResult:
    """The outcome of indexing every valid document in a ZIP archive."""

    archive: ArchiveIngestionResult
    indexed_documents: Sequence[IndexingResult]

    @property
    def chunk_count(self) -> int:
        return sum(result.chunk_count for result in self.indexed_documents)

    @property
    def inserted_chunk_count(self) -> int:
        return sum(result.inserted_chunk_count for result in self.indexed_documents)


@dataclass(frozen=True)
class PreparedContext:
    """The temporary system message and its retrieved source chunks."""

    system_message: str
    results: Sequence[SearchResult]
    rejected_results: Sequence[SearchResult] = ()


def format_source_attribution(results: Sequence[SearchResult]) -> str:
    """Return a concise, deterministic source list for a completed RAG answer.

    Attribution is generated by SensAI from the chunks it actually retrieved,
    rather than trusting the language model to invent or repeat citations.
    """
    sources: dict[str, list[str]] = {}
    for result in results:
        chunk_ids = sources.setdefault(result.source_filename, [])
        if result.chunk_id not in chunk_ids:
            chunk_ids.append(result.chunk_id)

    if not sources:
        return ""

    formatted_sources = [
        f"{filename} (chunks: {', '.join(chunk_ids)})"
        for filename, chunk_ids in sources.items()
    ]
    return f"Sources: {'; '.join(formatted_sources)}"


class RAGIndexer:
    """Run ingestion, chunking, embedding, and persistent storage in order."""

    def __init__(
        self,
        ingestor: DocumentIngestor | None = None,
        chunker: DocumentChunker | None = None,
        embedding_generator: EmbeddingGenerator | None = None,
        vector_store: LocalVectorStore | None = None,
    ) -> None:
        self.ingestor = ingestor or DocumentIngestor()
        self.chunker = chunker or DocumentChunker()
        self.embedding_generator = embedding_generator or EmbeddingGenerator()
        self.vector_store = vector_store or LocalVectorStore()

    def index_document(self, document_path: str | Path) -> IndexingResult | ArchiveIndexingResult:
        if Path(document_path).suffix.lower() == ".zip":
            return self.index_archive(document_path)
        document = self.ingestor.ingest(document_path)
        return self._index_ingested_document(document)

    def index_archive(self, archive_path: str | Path) -> ArchiveIndexingResult:
        archive = self.ingestor.ingest_archive(archive_path)
        indexed_documents = [
            self._index_ingested_document(document) for document in archive.documents
        ]
        return ArchiveIndexingResult(archive, indexed_documents)

    def clear_index(self) -> int:
        """Remove every stored document chunk and embedding from the local index."""
        return self.vector_store.clear()

    def _index_ingested_document(self, document: IngestedDocument) -> IndexingResult:
        chunks = self.chunker.chunk(document)
        embedded_chunks = self.embedding_generator.embed_chunks(chunks)
        inserted_chunk_count = self.vector_store.store_chunks(embedded_chunks)
        return IndexingResult(document, len(chunks), inserted_chunk_count)


class RAGContextProvider:
    """Retrieve evidence and turn it into a safe, bounded system message."""

    _INSTRUCTIONS = (
        "You are a document-grounded assistant. Answer only with information supported by the "
        "retrieved excerpts below. Do not include source citations, chunk identifiers, or line "
        "numbers in your answer: the CLI displays verified sources separately. If the excerpts "
        "do not contain the answer, say exactly: 'I cannot find this information in the "
        "indexed documents.' Do not use outside knowledge.\n\nRetrieved context:\n"
    )

    def __init__(
        self,
        embedding_generator: EmbeddingGenerator,
        vector_store: LocalVectorStore,
        config: RAGContextConfig | None = None,
    ) -> None:
        self.embedding_generator = embedding_generator
        self.vector_store = vector_store
        self.config = config or RAGContextConfig()

    def prepare(
        self,
        query: str,
        metadata_filter: MetadataFilter | None = None,
    ) -> PreparedContext:
        # Avoid an unnecessary Ollama embedding call when there is no knowledge
        # base. The model still receives the missing-context instruction.
        if self.vector_store.count_chunks() == 0:
            logger.info("rag.retrieval_skipped reason=empty_knowledge_base")
            return PreparedContext(self._build_message([]), [])

        query_embedding = self.embedding_generator.embed_query(query)
        if metadata_filter is None:
            retrieved_results = self.vector_store.search(query_embedding, top_k=self.config.top_k)
        else:
            retrieved_results = self.vector_store.search(
                query_embedding,
                top_k=self.config.top_k,
                metadata_filter=metadata_filter,
            )
        results, rejected_results = self._filter_by_relevance(retrieved_results)
        self._log_retrieval(results, rejected_results)
        return PreparedContext(self._build_message(results), results, rejected_results)

    def _filter_by_relevance(
        self,
        results: Sequence[SearchResult],
    ) -> tuple[list[SearchResult], list[SearchResult]]:
        selected_results = [
            result
            for result in results
            if result.similarity_score >= self.config.relevance_threshold
        ]
        rejected_results = [
            result
            for result in results
            if result.similarity_score < self.config.relevance_threshold
        ]
        return selected_results, rejected_results

    def _log_retrieval(
        self,
        selected_results: Sequence[SearchResult],
        rejected_results: Sequence[SearchResult],
    ) -> None:
        """Log score decisions without putting rejected text into the model prompt."""
        logger.info(
            "RAG relevance threshold %.3f; selected [%s]; rejected [%s]",
            self.config.relevance_threshold,
            self._describe_results(selected_results),
            self._describe_results(rejected_results),
        )

    @staticmethod
    def _describe_results(results: Sequence[SearchResult]) -> str:
        """Format retrieval decisions without exposing chunk text in logs."""
        return ", ".join(
            f"{result.source_filename}:{result.chunk_id}={result.similarity_score:.3f}"
            for result in results
        ) or "none"

    def _build_message(self, results: Sequence[SearchResult]) -> str:
        parts = [self._INSTRUCTIONS]
        if not results:
            return self._fit_to_budget("".join(parts) + "No relevant indexed excerpts were found.")

        for result in results:
            language = f" | Language: {result.language}" if result.language else ""
            source_header = (
                f"[Source: {result.source_filename} | Chunk: {result.chunk_id} | "
                f"Lines: {result.start_line}-{result.end_line}{language} | "
                f"Score: {result.similarity_score:.3f}]\n"
            )
            remaining = self.config.max_context_characters - len("".join(parts))
            if remaining <= len(source_header):
                break
            excerpt_budget = remaining - len(source_header) - 2
            excerpt = result.text[:excerpt_budget].rstrip()
            if not excerpt:
                break
            parts.append(f"{source_header}{excerpt}\n\n")

        return self._fit_to_budget("".join(parts))

    def _fit_to_budget(self, message: str) -> str:
        return message[: self.config.max_context_characters]
