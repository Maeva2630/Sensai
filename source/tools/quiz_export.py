"""Save a generated quiz to a file, through the permission layer."""
import json
from pathlib import Path
from typing import Any, Dict, Optional

from tools.base import ToolError
from tools.filesystem import FilesystemTool
from tools.permissions import PermissionChecker
from tools.structured_output import format_quiz

_ANSWER_FIELDS = ("answer_index", "explanation")


def render_quiz(quiz: Dict[str, Any], destination: Path, answers: bool = True) -> str:
    """The quiz as JSON for a `.json` file, as readable text otherwise."""
    if destination.suffix.lower() != ".json":
        return format_quiz(quiz, answers=answers)
    if not answers:
        quiz = {
            **quiz,
            "questions": [
                {key: value for key, value in question.items() if key not in _ANSWER_FIELDS}
                for question in quiz["questions"]
            ],
        }
    return json.dumps(quiz, indent=2, ensure_ascii=False) + "\n"


def save_quiz(quiz: Dict[str, Any], path: str, checker: Optional[PermissionChecker],
              answers: bool = True, overwrite: bool = False) -> Path:
    """Write the quiz to `path` and return the real path. Raises ToolError with a readable message."""
    if checker is None:
        raise ToolError("File export is not available: no permissions are loaded")
    destination = checker.require(path, "write")
    if destination.is_dir():
        raise ToolError(f"'{path}' is a directory")
    if destination.exists() and not overwrite:
        raise ToolError(f"File '{path}' already exists. Add --overwrite to replace it")
    try:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(render_quiz(quiz, destination, answers), encoding="utf-8")
    except OSError as e:
        raise ToolError(f"Could not write '{path}': {e.strerror or type(e).__name__}") from e
    return destination


class QuizStore:
    """Holds the last quiz generated by `/quiz`, so it can be exported without being retyped."""

    def __init__(self) -> None:
        self.quiz: Optional[Dict[str, Any]] = None


class SaveLastQuizTool(FilesystemTool):
    """Lets the model export the last quiz. The program writes it, the model never retypes it.

    The tool has no option to drop the answer key or to replace a file: a small model fills
    optional parameters at random. Those choices stay with the user, in `/quiz --save`.
    """

    name = "save_last_quiz"
    description = (
        "Save the quiz generated by the /quiz command, with its answer key, to a new file in an allowed "
        "directory. Use this to export a quiz instead of rewriting it with write_file."
    )
    parameters = {
        "type": "object",
        "properties": {
            "path": {"type": "string", "description": "Path of the file to create, for example exports/quiz.md."},
        },
        "required": ["path"],
    }
    # The result is our own fixed sentence, not text written by someone else
    untrusted = False

    def __init__(self, checker: PermissionChecker, store: QuizStore):
        super().__init__(checker)
        self._store = store

    def execute(self, arguments: Dict[str, Any]) -> str:
        if self._store.quiz is None:
            raise ToolError("No quiz has been generated yet. Ask the user to run /quiz first")
        save_quiz(self._store.quiz, arguments["path"], self._checker)
        return f"Quiz saved to '{arguments['path']}'"
